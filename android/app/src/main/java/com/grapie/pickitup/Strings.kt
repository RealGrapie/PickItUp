    /** "today, 00:57" / "yesterday, 23:10" / "12 Oct, 14:03" (with the year if not this year). */
    fun receivedWhen(at: Long, now: Long = System.currentTimeMillis()): String {
        val time = SimpleDateFormat("HH:mm", locale).format(Date(at))
        val day = Calendar.getInstance().apply { timeInMillis = at }
        val cal = Calendar.getInstance().apply { timeInMillis = now }
        fun same() = day.get(Calendar.YEAR) == cal.get(Calendar.YEAR) && day.get(Calendar.DAY_OF_YEAR) == cal.get(Calendar.DAY_OF_YEAR)
        if (same()) return today(time)
        cal.add(Calendar.DAY_OF_YEAR, -1)
        if (same()) return yesterday(time)
        val thisYear = day.get(Calendar.YEAR) == Calendar.getInstance().apply { timeInMillis = now }.get(Calendar.YEAR)
        return SimpleDateFormat(if (thisYear) "d MMM, HH:mm" else "d MMM yyyy, HH:mm", locale).format(Date(at))
    }

